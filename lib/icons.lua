-- Draws icon `name` with its top-left at (x, y).
function icons.draw(name, x, y, level)
  local rows = SHAPES[name]
  if not rows then return end
  screen.level(level or 15)
  for r = 1, #rows do
    local row = rows[r]
    for c = 1, #row do
      local ch = row:sub(c, c)
      if ch == "#" or ch == "/" then
        screen.rect(x + c - 1, y + r - 1, 1, 1)
      end
    end
  end
  screen.fill()
end

return icons
